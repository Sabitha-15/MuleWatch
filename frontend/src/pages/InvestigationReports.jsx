import { useState } from "react";
import { FileText, Printer, RefreshCw } from "lucide-react";

const API = "http://127.0.0.1:8000/api/phase2";
const panel = { background: "#FFFFFF", border: "1px solid #D7E0EC", borderRadius: 12, padding: 18 };
const field = { height: 40, border: "1px solid #CBD5E1", borderRadius: 8, padding: "0 10px", background: "#FFFFFF", color: "#172033" };
const button = { border: "1px solid #CBD5E1", borderRadius: 8, padding: "9px 13px", background: "#FFFFFF", color: "#1D4ED8", fontWeight: 600, cursor: "pointer" };
const currency = (v) => new Intl.NumberFormat("en-IN", { style: "currency", currency: "INR", maximumFractionDigits: 2 }).format(Number(v || 0));

export default function InvestigationReports() {
  const [caseId, setCaseId] = useState("1");
  const [investigatorId, setInvestigatorId] = useState("");
  const [report, setReport] = useState(null);
  const [history, setHistory] = useState([]);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  async function loadHistory(id = caseId) {
    const response = await fetch(`${API}/cases/${id}/reports`);
    const data = await response.json();
    if (!response.ok) throw new Error(data.detail || "Unable to load report history.");
    setHistory(data.reports || []);
  }

  async function generate(event) {
    event.preventDefault(); setLoading(true); setError(""); setReport(null);
    try {
      const response = await fetch(`${API}/cases/${caseId}/reports`, {
        method: "POST", headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ investigator_id: investigatorId ? Number(investigatorId) : null }),
      });
      const data = await response.json();
      if (!response.ok) throw new Error(data.detail || "Report generation failed.");
      setReport(data); await loadHistory();
    } catch (err) { setError(err.message); }
    finally { setLoading(false); }
  }

  async function openReport(id) {
    setLoading(true); setError("");
    try {
      const response = await fetch(`${API}/reports/${id}`);
      const data = await response.json();
      if (!response.ok) throw new Error(data.detail || "Unable to open report.");
      setReport(data);
    } catch (err) { setError(err.message); }
    finally { setLoading(false); }
  }

  return (
    <section style={{ maxWidth: 1500, margin: "0 auto" }}>
      <div className="page-header"><div><p className="page-eyebrow">PHASE 2 · STORED DATABASE REPORTS</p><h1>Investigation Reports</h1><p className="page-description">Generate immutable case-report snapshots containing account details, linked transactions, investigator notes and case-status history.</p></div><button style={button} onClick={() => loadHistory().catch((e) => setError(e.message))}><RefreshCw size={15} style={{ verticalAlign: "middle", marginRight: 6 }} />Refresh History</button></div>
      <div style={{ ...panel, marginBottom: 16 }}>
        <form onSubmit={generate} style={{ display: "flex", gap: 12, alignItems: "end", flexWrap: "wrap" }}>
          <label style={{ display: "grid", gap: 5, fontSize: 11, color: "#64748B" }}>Fraud Case ID<input style={{ ...field, width: 180 }} type="number" min="1" required value={caseId} onChange={(e) => setCaseId(e.target.value)} /></label>
          <label style={{ display: "grid", gap: 5, fontSize: 11, color: "#64748B" }}>Generated by Investigator ID (optional)<input style={{ ...field, width: 250 }} type="number" min="1" value={investigatorId} onChange={(e) => setInvestigatorId(e.target.value)} placeholder="e.g. 1" /></label>
          <button style={{ ...button, background: "#1D4ED8", color: "white" }} type="submit" disabled={loading}><FileText size={15} style={{ verticalAlign: "middle", marginRight: 6 }} />{loading ? "Generating..." : "Generate Report"}</button>
        </form>
      </div>
      {error && <div style={{ ...panel, color: "#B91C1C", marginBottom: 14 }}>{error}</div>}
      <div style={{ ...panel, marginBottom: 16 }}>
        <strong>Previously Generated Reports</strong>
        <div style={{ display: "flex", flexWrap: "wrap", gap: 8, marginTop: 12 }}>
          {history.map((item) => <button key={item.report_id} style={button} onClick={() => openReport(item.report_id)}>Report #{item.report_id} · {new Date(item.generated_at).toLocaleString("en-IN")}</button>)}
          {!history.length && <span style={{ fontSize: 12, color: "#64748B" }}>Enter a case ID and generate a report to create the first snapshot. Use Refresh History to load saved reports.</span>}
        </div>
      </div>
      {report?.report_data && <article id="case-report" style={panel}>
        <div style={{ display: "flex", justifyContent: "space-between", gap: 12, alignItems: "center", marginBottom: 16 }}><div><p className="page-eyebrow">MULEWATCH · INVESTIGATION RECORD</p><h2 style={{ margin: 0 }}>Case Report #{report.report_id}</h2><p style={{ color: "#64748B", fontSize: 12 }}>Case #{report.case_id} · Generated {new Date(report.generated_at).toLocaleString("en-IN")}</p></div><button style={button} onClick={() => window.print()}><Printer size={15} style={{ verticalAlign: "middle", marginRight: 6 }} />Print / Save PDF</button></div>
        <div style={{ display: "grid", gridTemplateColumns: "repeat(auto-fit,minmax(160px,1fr))", gap: 10, marginBottom: 18 }}>
          {[ ["Case title", report.report_data.case?.case_title], ["Status", report.report_data.case?.case_status], ["Priority", report.report_data.case?.priority], ["Account", report.report_data.account?.account_number], ["Customer", report.report_data.customer?.full_name], ["Investigator", report.report_data.investigator?.full_name || "Unassigned"] ].map(([label, value]) => <div key={label} style={{ padding: 12, border: "1px solid #E2E8F0", borderRadius: 9, background: "#F8FAFC" }}><div style={{ color: "#64748B", fontSize: 10, textTransform: "uppercase", fontWeight: 700 }}>{label}</div><strong style={{ display: "block", marginTop: 6, fontSize: 13 }}>{value || "—"}</strong></div>)}
        </div>
        <h3>Case Description</h3><p style={{ color: "#475569", whiteSpace: "pre-wrap" }}>{report.report_data.case?.case_description || "No description recorded."}</p>
        <h3>Linked Transactions ({report.report_data.transactions?.length || 0})</h3>
        <div style={{ overflowX: "auto" }}><table style={{ width: "100%", borderCollapse: "collapse", fontSize: 12 }}><thead><tr style={{ textAlign: "left", background: "#F8FAFC" }}>{["Transaction", "Time", "From", "To", "Amount", "Status"].map((h) => <th key={h} style={{ padding: 9, borderBottom: "1px solid #E2E8F0" }}>{h}</th>)}</tr></thead><tbody>{(report.report_data.transactions || []).map((t) => <tr key={t.transaction_id}>{[t.transaction_id, new Date(t.txn_time).toLocaleString("en-IN"), t.sender_account_id, t.receiver_account_id, currency(t.amount), t.status].map((v, i) => <td key={i} style={{ padding: 9, borderBottom: "1px solid #EEF2F7" }}>{v}</td>)}</tr>)}</tbody></table></div>
        <h3>Investigator Notes ({report.report_data.notes?.length || 0})</h3>{(report.report_data.notes || []).map((n) => <div key={n.note_id} style={{ padding: 10, borderLeft: "3px solid #2563EB", background: "#F8FAFC", marginBottom: 8 }}><p style={{ margin: 0, whiteSpace: "pre-wrap" }}>{n.note_text}</p><small style={{ color: "#64748B" }}>{n.investigator_name || "Investigator"} · {new Date(n.created_at).toLocaleString("en-IN")}</small></div>)}
        <h3>Case Status History ({report.report_data.status_history?.length || 0})</h3>{(report.report_data.status_history || []).map((h) => <div key={h.history_id} style={{ fontSize: 12, padding: "8px 0", borderBottom: "1px solid #EEF2F7" }}>{h.old_status || "NEW"} → <strong>{h.new_status}</strong> · {new Date(h.changed_at).toLocaleString("en-IN")} · {h.change_reason || "No reason recorded"}</div>)}
        <p style={{ marginTop: 18, color: "#64748B", fontSize: 11 }}>This is a point-in-time snapshot. Later case changes require generating a new report. A risk score is an investigation indicator, not proof of fraud.</p>
      </article>}
    </section>
  );
}
